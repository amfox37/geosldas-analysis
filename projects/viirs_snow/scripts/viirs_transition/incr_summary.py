#!/usr/bin/env python3
"""Tables and figures for analysis B (docs/viirs_transition_plan.md), from output/incr_stats/{incr_stats,innov}_<arm>.nc.

Writes docs/viirs_transition_report_figures/B_summary.md (tables) and B_*.png.
Exclusions applied identically to every arm: days listed as input gaps (zero_obs_days.csv rows of <= 20 days: Aqua
2022-04-02..16, Terra 2022-10-11..22, Terra 2025-05-11..14, J2 2024-02-28) and 2023-08-01 (segment boundary day).
Only tiles north of 30N are used for the headline numbers (bands N_30_45, N_45_60, N_60_90), where snow DA acts.
Python: /usr/local/other/GEOSpyD/25.3.1-0/2025-10-07/envs/py3.13/bin/python3 -I incr_summary.py
"""
import csv, datetime as dt, json
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import netCDF4
import numpy as np

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]
CFG = json.load(open(PROJECT / "config" / "arms.json"))
IN = PROJECT / "output" / "incr_stats"
FIG = PROJECT / "docs" / "viirs_transition_report_figures"
ARMS = [a for a in CFG["arms"] if a != "OL" and (IN / f"incr_stats_{a}.nc").exists()]   # OL writes no catch_progn_incr (getinnov only)
IARMS = [a for a in CFG["arms"] if (IN / f"innov_{a}.nc").exists()]
SY = CFG["snow_years"]
NB, NL = 5, 8
NHB = [2, 3, 4]                                    # bands >= 30N
BN = ["S_hemisphere", "N_0_30", "N_30_45", "N_45_60", "N_60_90"]
COL = {"OL": "#898781", "T_to_J2": "#2a78d6", "TA_to_J1J2": "#eb6834", "T_control": "#1baf7a", "TA_control": "#6250d6"}
SPN = ["Aqua", "Terra", "J1", "J2"]


def dates(arr):
    return np.array([dt.date(int(x) // 10000, int(x) // 100 % 100, int(x) % 100) for x in arr])


def excl_days():
    ex = set()
    for r in csv.DictReader(open(PROJECT / "output" / "obs_availability" / "zero_obs_days.csv")):
        if int(r["n_days"]) <= 20:
            b = dt.datetime.strptime(r["first_day"], "%Y%m%d").date(); e = dt.datetime.strptime(r["last_day"], "%Y%m%d").date()
            ex |= {b + dt.timedelta(i) for i in range((e - b).days + 1)}
    ex.add(dt.date(2023, 8, 1))
    return ex


EX = excl_days()


def sy_masks(dd):
    ok = np.array([d not in EX for d in dd])
    return {s["id"]: ok & np.array([dt.date.fromisoformat(s["beg"]) <= d <= dt.date.fromisoformat(s["end"]) for d in dd]) for s in SY}


def grp_nh(a):
    """sum over the NH groups (bands >= 30N) of the trailing 'grp' axis -> (..., ) """
    a = a.reshape(a.shape[:-1] + (NB, NL))
    return a[..., NHB, :].sum((-1, -2))


def main():
    S = {}
    for a in ARMS:
        d = netCDF4.Dataset(IN / f"incr_stats_{a}.nc"); d.set_auto_mask(False)
        S[a] = {k: d[k][:] for k in ("date", "n_tiles_by_nsteps", "dbl", "step_n", "step_net", "step_abs", "step_cap", "dbl_gap", "tile_net", "tile_abs", "tile_n_steps", "tile_n_cap", "tile_n_days", "tile_n_double_days", "lat")}
        S[a]["dd"] = dates(S[a]["date"])
    md = ["# Analysis B: update structure and increments (auto-generated by `incr_summary.py`)\n",
          "North of 30N only (bands N_30_45, N_45_60, N_60_90); all days of each snow year (1 Aug to 31 Jul) except the excluded days "
          f"({len(EX)} days: input gaps and 2023-08-01) which are dropped from every arm. An increment is |sum of the 3 layer WESN increments| >= 0.01 kg m-2; "
          "cap = |incr| >= 4.995 kg m-2 (SCF_ANA_MAXINCRSWE 5). Tile-days are summed over days and tiles.\n"]
    # ---- table 1: number of increments per tile-day
    rows1, rows2, rows3 = [], [], []
    R = {}
    for a in ARMS:
        m = sy_masks(S[a]["dd"])
        for s in SY:
            mk = m[s["id"]]
            if not mk.any():
                continue
            ntn = grp_nh(S[a]["n_tiles_by_nsteps"][mk]).sum(0)            # (4,)
            n_any = ntn[1:].sum()
            dbl = grp_nh(S[a]["dbl"][mk]).sum(0)                         # (6,)
            cap = grp_nh(S[a]["step_cap"][mk]).sum(); nnz = grp_nh(S[a]["step_n"][mk]).sum()
            net = grp_nh(S[a]["step_net"][mk]).sum(); ab = grp_nh(S[a]["step_abs"][mk]).sum()
            nd = mk.sum()
            R[(a, s["id"])] = dict(n_any=n_any, ntn=ntn, dbl=dbl, cap=cap, nnz=nnz, net=net, ab=ab, nd=nd)
            rows1.append((a, s["id"], nd, n_any / nd, ntn[1] / max(n_any, 1) * 100, ntn[2] / max(n_any, 1) * 100, ntn[3] / max(n_any, 1) * 100))
            if dbl[0] > 0:
                rows2.append((a, s["id"], dbl[0] / nd, dbl[1] / dbl[0] * 100, dbl[2] / dbl[0], dbl[3] / dbl[0], dbl[4] / dbl[5] * 100))
            rows3.append((a, s["id"], net / nd, ab / nd, net / max(ab, 1e-9) * 100, cap / max(nnz, 1) * 100, nnz / nd))
    md.append("## B1. Tiles with an increment per day, and number of increment steps per tile-day\n")
    md.append("| arm | SY | days | tiles with >=1 incr / day | % of those with 1 step | % with 2 | % with >=3 |\n|---|---|---|---|---|---|---|")
    md += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]:.0f} | {r[4]:.1f} | {r[5]:.1f} | {r[6]:.1f} |" for r in rows1]
    md.append("\n## B2. Tiles with >=2 increments in a day: first vs second increment\n")
    md.append("Means over double tile-days; 'same sign' = both increments add (or both remove) snow; pair net/abs = |net of the two| over sum of |two| "
              "(100% = fully reinforcing, 0% = full cancellation, negative = net opposes the first).\n")
    md.append("| arm | SY | double tiles / day | % same sign | mean abs first (kg m-2) | mean abs second | pair net / abs (%) |\n|---|---|---|---|---|---|---|")
    md += [f"| {r[0]} | {r[1]} | {r[2]:.0f} | {r[3]:.1f} | {r[4]:.2f} | {r[5]:.2f} | {r[6]:.1f} |" for r in rows2]
    md.append("\n## B3. Increment totals, net/abs and cap hits (kg m-2 per day, summed over tiles / N tiles north of 30N is not applied: values are domain-sum per day divided by tile count N30)\n")
    nN = int(((S[ARMS[0]]["lat"] >= 30)).sum())
    md.append(f"N tiles with lat >= 30N = {nN}. 'net' and 'abs' = mean per tile per year (kg m-2 yr-1) = (sum of increments over the year) / N.\n")
    md.append("| arm | SY | net (kg m-2 yr-1) | abs (kg m-2 yr-1) | net/abs % | % of increments at cap | incr steps / day |\n|---|---|---|---|---|---|---|")
    for r in rows3:
        a, sid = r[0], r[1]
        x = R[(a, sid)]
        md.append(f"| {a} | {sid} | {x['net'] / nN * 365.0 / x['nd']:.2f} | {x['ab'] / nN * 365.0 / x['nd']:.2f} | {r[4]:.1f} | {r[5]:.2f} | {r[6]:.0f} |")
    # tile-level annual net/abs (from tile arrays) -> distribution check
    # ---- figure B_1: step-class fractions
    fig, ax = plt.subplots(figsize=(10, 4))
    w = 0.16
    for i, a in enumerate(ARMS):
        vals = [(R[(a, s["id"])]["ntn"][2] + R[(a, s["id"])]["ntn"][3]) / max(R[(a, s["id"])]["n_any"], 1) * 100 if (a, s["id"]) in R else np.nan for s in SY]
        ax.bar(np.arange(len(SY)) + (i - 1.5) * w, vals, w, color=COL[a], label=a)
    ax.set_xticks(range(len(SY))); ax.set_xticklabels([s["id"] for s in SY]); ax.set_ylabel("% of increment tile-days with >= 2 steps (N of 30N)")
    ax.legend(frameon=False, ncol=5, fontsize=8); fig.tight_layout(); fig.savefig(FIG / "B_1_double_fraction.png", dpi=130); plt.close(fig)
    # ---- figure B_2: UTC step x lon sector pattern (SY2 pre, SY5 post), per arm
    fig, axs = plt.subplots(2, len(ARMS), figsize=(3.0 * len(ARMS), 5.2), sharey=True)
    for j, a in enumerate(ARMS):
        m = sy_masks(S[a]["dd"])
        for i, sid in enumerate(("SY2", "SY5")):
            ax = axs[i, j]; mk = m[sid]
            if not mk.any():
                ax.axis("off"); continue
            h = S[a]["step_n"][mk].sum(0).reshape(8, NB, NL)[:, NHB, :].sum(1) / mk.sum()
            im = ax.imshow(h, aspect="auto", origin="lower", cmap="viridis")
            ax.set_title(f"{a} {sid}", fontsize=8); ax.set_xticks(range(NL)); ax.set_xticklabels([f"{-180 + 45 * k}" for k in range(NL)], fontsize=6)
            ax.set_yticks(range(8)); ax.set_yticklabels([f"{3 * k:02d}z" for k in range(8)], fontsize=6)
    fig.suptitle("Tiles with an increment per day by UTC step (rows) and 45-deg longitude sector (cols), N of 30N", fontsize=9)
    fig.tight_layout(); fig.savefig(FIG / "B_2_step_by_longitude.png", dpi=130); plt.close(fig)
    # ---- figure B_3: net/abs and cap
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.8))
    for i, a in enumerate(ARMS):
        axs[0].bar(np.arange(len(SY)) + (i - 1.5) * w, [R[(a, s["id"])]["net"] / max(R[(a, s["id"])]["ab"], 1e-9) * 100 if (a, s["id"]) in R else np.nan for s in SY], w, color=COL[a], label=a)
        axs[1].bar(np.arange(len(SY)) + (i - 1.5) * w, [R[(a, s["id"])]["cap"] / max(R[(a, s["id"])]["nnz"], 1) * 100 if (a, s["id"]) in R else np.nan for s in SY], w, color=COL[a])
    axs[0].set_ylabel("net / abs increment (%)"); axs[1].set_ylabel("% of increments at the 5 kg m-2 cap")
    for ax in axs:
        ax.set_xticks(range(len(SY))); ax.set_xticklabels([s["id"] for s in SY])
    axs[0].legend(frameon=False, fontsize=7, ncol=2); fig.tight_layout(); fig.savefig(FIG / "B_3_netabs_cap.png", dpi=130); plt.close(fig)
    # ---- innovations
    md.append("\n## B4. Innovations (obs - forecast) of the second sensor, by arm\n")
    md.append("Tiles north of 30N where both sensors of a pair have an obs that day (Terra+Aqua; J1+J2). OmF mean and RMS in SCF units (0-1 fraction as stored in ObsFcstAna). "
              "Aqua (13:30, step after Terra) forecasts contain the Terra update in the arms that assimilate Terra. Excluded days as above; "
              "MODIS columns end 2025-12-31 for the OL/VIIRS arms (no monitor obs in 2026), so MODIS rows are restricted to days up to 2025-12-31 for every arm.\n")
    md.append("| arm | SY | species | n tile-days / day | mean OmF | RMS OmF | mean abs OmF | frac assimilated |\n|---|---|---|---|---|---|---|---|")
    IV = {}
    for a in IARMS:
        p = IN / f"innov_{a}.nc"
        if not p.exists():
            continue
        d = netCDF4.Dataset(p); d.set_auto_mask(False); st = d["stats"][:]; dd = dates(d["date"][:])
        m = sy_masks(dd)
        for s in SY:
            mk = m[s["id"]].copy()
            for si, sp in enumerate(SPN):
                mk2 = mk & np.array([(x <= dt.date(2025, 12, 31)) if sp in ("Aqua", "Terra") else True for x in dd])
                if not mk2.any():
                    continue
                x = st[mk2][:, si, 1][:, NHB].sum((0, 1))                # var vector
                if x[0] < 1:
                    continue
                IV[(a, s["id"], sp)] = (x[1] / x[0], np.sqrt(x[2] / x[0]), x[3] / x[0], x[6] / x[0], x[0] / mk2.sum())
                v = IV[(a, s["id"], sp)]
                md.append(f"| {a} | {s['id']} | {sp} | {v[4]:.0f} | {v[0]:+.4f} | {v[1]:.4f} | {v[2]:.4f} | {v[3]:.2f} |")
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.8))
    for k, sp in enumerate(("Aqua", "J2")):
        for i, a in enumerate(IARMS):
            axs[k].bar(np.arange(len(SY)) + (i - 2) * w, [IV.get((a, s["id"], sp), (np.nan,) * 5)[1] for s in SY], w, color=COL[a], label=a)
        axs[k].set_title(f"{sp} RMS OmF, pair tiles N of 30N", fontsize=9); axs[k].set_xticks(range(len(SY))); axs[k].set_xticklabels([s["id"] for s in SY])
    axs[0].legend(frameon=False, fontsize=7, ncol=2); fig.tight_layout(); fig.savefig(FIG / "B_4_second_sensor_innov.png", dpi=130); plt.close(fig)
    (FIG / "B_summary.md").write_text("\n".join(md) + "\n")
    print("wrote", FIG / "B_summary.md")


if __name__ == "__main__":
    main()
